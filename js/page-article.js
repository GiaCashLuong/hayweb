const vi = currentLang === 'vi';

function buildPage() {
  const params = new URLSearchParams(window.location.search);
  const slug = params.get('slug') || '';
  const a = articles[slug];

  if (!a) {
    document.getElementById('article-title').textContent = vi ? 'Bài viết không tồn tại' : 'Article not found';
    document.getElementById('article-content').innerHTML = `<p><a href="/guides">${vi ? '← Quay lại hướng dẫn' : '← Back to guides'}</a></p>`;
    return;
  }

  // Meta
  const title = vi ? a.titleVI : a.titleEN;
  document.title = `${title} – HAYWEB`;
  document.getElementById('page-title').textContent = `${title} – HAYWEB`;
  document.getElementById('page-desc').setAttribute('content', vi ? a.titleVI : a.titleEN);

  // Hero
  document.getElementById('article-back').textContent = vi ? '← Hướng dẫn' : '← Guides';
  document.getElementById('article-tag').textContent = vi ? a.tagVI : a.tagEN;
  document.getElementById('article-time').textContent = vi ? a.timeVI : a.timeEN;
  document.getElementById('article-title').textContent = title;

  // Cover image
  const img = document.getElementById('article-cover-img');
  img.src = a.img;
  img.alt = title;

  // Content
  document.getElementById('article-content').innerHTML = vi ? a.contentVI : a.contentEN;

  // Sidebar
  document.getElementById('sidebar-label').textContent = vi
    ? 'Sẵn sàng bắt đầu dự án của bạn?'
    : 'Ready to start your project?';
  document.getElementById('sidebar-btn').textContent = vi ? 'Nhận báo giá ngay' : 'Get a quote';

  // Build TOC from h2s
  const h2s = document.querySelectorAll('.article-content h2');
  if (h2s.length > 0) {
    let tocHTML = `<h4>${vi ? 'Nội dung' : 'Contents'}</h4><ul>`;
    h2s.forEach((h, i) => {
      const id = `section-${i}`;
      h.id = id;
      tocHTML += `<li><a href="#${id}">${h.textContent}</a></li>`;
    });
    tocHTML += '</ul>';
    document.getElementById('article-toc').innerHTML = tocHTML;
  }

  // CTA
  document.getElementById('cta-title').innerHTML = vi
    ? 'Muốn áp dụng điều này cho <em>dự án của bạn?</em>'
    : 'Want to apply this to <em>your project?</em>';
  document.getElementById('cta-desc').textContent = vi
    ? 'Đội ngũ HAYWEB tư vấn miễn phí và báo giá trong 5 phút.'
    : 'HAYWEB team offers free consultation and quotes in 5 minutes.';
  document.getElementById('cta-btn').textContent = vi ? 'Bắt đầu ngay' : 'Get started';
}

async function init() {
  await renderNav('guides');
  renderFooter();
  buildPage();
  initScrollReveal();
}

